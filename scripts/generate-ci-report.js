   // scripts/generate-ci-report.js
   import { execSync } from 'node:child_process';
   import { readFileSync, writeFileSync, appendFileSync } from 'node:fs';
   import { fileURLToPath } from 'node:url';
   import { dirname, join } from 'node:path';

   const __filename = fileURLToPath(import.meta.url);
   const __dirname = dirname(__filename);
   const rootDir = join(__dirname, '..');

   console.log('🚀 Starting Automated CI Report Generation...\n');

   // 1. Run a quick CI benchmark (100 pages, N=10)
   console.log('⏱️  Running quick crawler benchmark (100 pages, N=10)...');
   try {
     // We temporarily set PAGES=100 for a fast CI run
     const output = execSync('PAGES=100 node crawler/crawler-bounded.js 10', { 
       cwd: rootDir, 
       encoding: 'utf-8',
       env: { ...process.env, PAGES: '100' }
     });
     
     // Extract time from output (e.g., "Bounded Crawler (N=10): 2.145s")
     const timeMatch = output.match(/Bounded Crawler \(N=10\): ([\d.]+[a-z]+)/i);
     const crawlTime = timeMatch ? timeMatch[1] : 'Unknown';
     
     console.log(`✅ Crawler finished in ${crawlTime}\n`);

     // 2. Run Coverage
     console.log('📊 Generating Code Coverage Report...');
     const coverageOutput = execSync('npm run test:coverage', { 
       cwd: join(rootDir, 'api-client'), 
       encoding: 'utf-8' 
     });
     
     // Extract total coverage percentage
     const coverageMatch = coverageOutput.match(/All files\s*\|\s*([\d.]+)/);
     const coveragePercent = coverageMatch ? coverageMatch[1] + '%' : 'Unknown';
     console.log(`✅ Total Coverage: ${coveragePercent}\n`);

     // 3. Generate Markdown Snippet
     const timestamp = new Date().toISOString();
     const ciReport = `\n\n---\n## 🤖 Automated CI Report (Generated: ${timestamp})\n\n### Live Benchmark Results\n- **Crawler (100 pages, N=10)**: ${crawlTime}\n- **Code Coverage**: ${coveragePercent}\n\n*This section is automatically generated by the GitHub Actions CI pipeline.*\n`;

     // 4. Append to REPORT.md
     const reportPath = join(rootDir, 'REPORT.md');
     appendFileSync(reportPath, ciReport);
     console.log('📝 Successfully appended live metrics to REPORT.md');

   } catch (error) {
     console.error('❌ Error generating report:', error.message);
     process.exit(1);
   }