// scripts/generate-ci-report.js
import { execSync } from 'node:child_process';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = join(__dirname, '..');

console.log('🚀 Starting Automated CI Report Generation...\n');

try {
  // 1. Run Coverage (this is the most important metric)
  console.log('📊 Generating Code Coverage Report...');
  const coverageOutput = execSync('npm run test:coverage', { 
    cwd: join(rootDir, 'api-client'), 
    encoding: 'utf-8',
    stdio: 'pipe'
  });
  
  // Extract total coverage percentage
  const coverageMatch = coverageOutput.match(/All files\s*\|\s*([\d.]+)/);
  const coveragePercent = coverageMatch ? coverageMatch[1] + '%' : 'N/A';
  console.log(`✅ Total Coverage: ${coveragePercent}\n`);

  // 2. Generate Markdown Snippet
  const timestamp = new Date().toISOString();
  const ciReport = `\n\n---\n## 🤖 Automated CI Report (Generated: ${timestamp})\n\n### Code Coverage\n- **Total Coverage**: ${coveragePercent}\n\n### Test Results\n- ✅ All tests passed with fake clock\n- ✅ Deterministic execution (milliseconds)\n\n*This section is automatically generated by the GitHub Actions CI pipeline.*\n`;

  // 3. Update REPORT.md
  const reportPath = join(rootDir, 'REPORT.md');
  
  // Read existing report (using ES module readFileSync)
  let currentReport = existsSync(reportPath) ? 
    readFileSync(reportPath, 'utf-8') : '';
  
  // Remove old automated section if it exists (to avoid duplication on re-runs)
  const automatedSectionStart = currentReport.indexOf('## 🤖 Automated CI Report');
  if (automatedSectionStart !== -1) {
    currentReport = currentReport.substring(0, automatedSectionStart);
  }
  
  // Write back the cleaned report + new section
  writeFileSync(reportPath, currentReport + ciReport);
  console.log('✅ Successfully appended coverage metrics to REPORT.md');

} catch (error) {
  console.error('❌ Error generating report:', error.message);
  console.error('stderr:', error.stderr?.toString());
  process.exit(1);
}